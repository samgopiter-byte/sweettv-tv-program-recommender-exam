"""Extended independent checks for the final model (numbers for the report section "What I personally checked").

Every block recomputes a number by a second route or tests the evaluation itself, and prints both values.
Output is also written to verification_numbers_v2.md.
"""
import csv
import datetime as dt
import hashlib
import io
import time
import numpy as np
import pandas as pd

import methods as m
import rerank as rr
from common import Split, ROOT, K, W11, W23, W31, W43, WATCH_ABS_S, WATCH_FRAC, ap_at_k, evaluate, user_item, test_users
from final2 import HIST_DEP, LGB, ROUNDS, feature_idx

RAW = ROOT / "data" / "raw"
buf = io.StringIO()


def say(*a):
    s = " ".join(str(x) for x in a)
    print(s, flush=True)
    buf.write(s + "\n")


def per_user_ap(lists, truth, users):
    return np.array([ap_at_k(lists[u], truth[u]) for u in users if u in truth])


def boot(a, b, B=2000, seed=0):
    d = a - b
    idx = np.random.default_rng(seed).integers(0, len(d), size=(B, len(d)))
    means = d[idx].mean(axis=1)
    return d.mean(), np.percentile(means, [2.5, 97.5])


say("# Verification numbers, final model (generated by src/verify2.py)\n")

# ---- fold data and lists for the compared methods -------------------------------------------------------
data = {mode: rr.get_D(mode) for mode in ("val", "val2")}
n_users = len(data["val"][1].sel)
names = list(data["val"][3]["names"])
idx = feature_idx(names)
Ds_sub = [dict(data[mo][3], X=data[mo][3]["X"][:, idx]) for mo in ("val", "val2")]
preds, _ = rr.crossfit_pooled(Ds_sub, n_users, rounds=ROUNDS, params=LGB)
L = {}
for mo, pr in zip(("val", "val2"), preds):
    sp, M, fb, D = data[mo]
    pop = m.pop_ranking(sp.train_ui, sp.pool, "seconds")[:K]
    L[mo] = {
        "popularity": {u: pop for u in sp.users},
        "personal history": m.recommend(M, m.personal_scores(M), fb),
        "blend (habit + personal x exposure)": rr.lists_from_scores(sp, M, fb, D["rows"], D["cols"], D["X"][:, names.index("blend")]),
        "final re-ranker": rr.lists_from_scores(sp, M, fb, D["rows"], D["cols"], pr),
    }

# ---- V1: paired bootstrap over users -----------------------------------------------------------------------
say("## V1. Are the differences larger than the noise? Paired bootstrap over users (2000 resamples)")
for mo in ("val", "val2"):
    sp = data[mo][0]
    users = [u for u in sp.users if u in sp.truth]
    ap = {k: per_user_ap(v, sp.truth, users) for k, v in L[mo].items()}
    say(f"- fold {mo} ({len(users)} users): " + "; ".join(f"{k} {v.mean():.4f}" for k, v in ap.items()))
    for a_, b_ in (("final re-ranker", "blend (habit + personal x exposure)"), ("final re-ranker", "personal history"),
                   ("final re-ranker", "popularity"), ("personal history", "popularity")):
        mean, ci = boot(ap[a_], ap[b_])
        say(f"  {a_} minus {b_}: {mean:+.4f}, 95% CI [{ci[0]:+.4f}, {ci[1]:+.4f}]{'  (includes 0)' if ci[0] <= 0 <= ci[1] else ''}")

# ---- V2: permutation canary ---------------------------------------------------------------------------------
say("\n## V2. Canary: give every user another user's list (personalisation destroyed)")
for mo in ("val", "val2"):
    sp = data[mo][0]
    users = [u for u in sp.users if u in sp.truth]
    rng = np.random.default_rng(1)
    for name in ("final re-ranker", "personal history"):
        lists = L[mo][name]
        real = np.mean(per_user_ap(lists, sp.truth, users))
        shuf = []
        for s_ in range(20):
            perm = rng.permutation(len(sp.users))
            swapped = {u: lists[sp.users[perm[i]]] for i, u in enumerate(sp.users)}
            shuf.append(np.mean(per_user_ap(swapped, sp.truth, users)))
        say(f"- {mo} {name}: real MAP@5 {real:.4f}; shuffled across users (mean of 20) {np.mean(shuf):.4f} (min {np.min(shuf):.4f}, max {np.max(shuf):.4f})")

# ---- V3: leak canary: what a 14-day peek into the target window would look like -----------------------------
say("\n## V3. Canary: allow the history to peek 14 days into the target window (this is what a leak looks like)")
sp, M, fb, D = data["val"]
honest = evaluate(L["val"]["personal history"], sp.truth, sp.users)["MAP@5"]
ui_leak = user_item(sp.inter, W11, W23 + 14 * 86400)
ui_leak = ui_leak[ui_leak["tv_show_id"].isin(sp.pool)].sort_values(["user_id", "sec"], ascending=[True, False])
top = {u: g["tv_show_id"].tolist()[:K] for u, g in ui_leak.groupby("user_id", sort=False)}
fbk = m.pop_ranking(sp.train_ui, sp.pool, "seconds")[:20]
leaked = {u: m.pad_to_k(top.get(u, []), fbk) for u in sp.users}
say(f"- personal-history baseline, fold val: honest cutoff {honest:.4f}; with 14 days of the target window leaked into the history {evaluate(leaked, sp.truth, sp.users)['MAP@5']:.4f}")

# ---- V4: independent recount of one programme (popularity) --------------------------------------------------
say("\n## V4. Independent recount of the most popular programme (different code route, raw files only)")
sp, M, fb, D = data["val"]
pid = m.pop_ranking(sp.train_ui, sp.pool, "users")[0]
sched_raw = pd.concat([pd.read_csv(RAW / f, encoding="utf-8") for f in ("export_arh_11-20-final.csv", "export_arh_21-30-final.csv")])
sched_raw = sched_raw[sched_raw["tv_show_id"] == pid].copy()
epoch = pd.Timestamp("1970-01-01")
sched_raw["start"] = ((pd.to_datetime(sched_raw["start_time"], format="%d.%m.%Y %H:%M:%S") - epoch) // pd.Timedelta("1s")).astype(np.int64)
sched_raw["end"] = sched_raw["start"] + sched_raw["duration"].astype(np.int64)
sched_raw = sched_raw[(sched_raw["start"] < W23) & (sched_raw["end"] > W11)]
chans = set(sched_raw["channel_id"])
v = pd.read_csv(RAW / "dataset11-30.csv", dtype={"user_id": "uint64"})
v = v[v["vsetv_id"].isin(chans)]
v["s"] = ((pd.to_datetime(v["start_time"]) - epoch) // pd.Timedelta("1s")).astype(np.int64)
v["e"] = ((pd.to_datetime(v["stop_time"]) - epoch) // pd.Timedelta("1s")).astype(np.int64)
secs, dur = {}, {}
for r in sched_raw.itertuples():
    w = v[v["vsetv_id"] == r.channel_id]
    ov = np.minimum(np.minimum(w["e"].values, r.end), W23) - np.maximum(np.maximum(w["s"].values, r.start), W11)
    ok = ov > 0
    dur[r.start] = r.duration
    for u, x in zip(w["user_id"].values[ok], ov[ok]):
        secs[(u, r.start)] = secs.get((u, r.start), 0) + int(x)
watched = {k: x for k, x in secs.items() if x >= min(WATCH_ABS_S, WATCH_FRAC * dur[k[1]])}
users_re = {k[0] for k in watched}
row = sp.train_ui[sp.train_ui["tv_show_id"] == pid]
say(f"- programme {pid}: recount -> {len(users_re)} users, {sum(watched.values())} watched seconds, {len(watched)} watched user-airings | pipeline -> {len(row)} users, {int(row['sec'].sum())} seconds, {int(row['n'].sum())} user-airings | equal={len(users_re) == len(row) and sum(watched.values()) == int(row['sec'].sum())}")
dup = sched_raw.groupby("start")["channel_id"].nunique()
say(f"- design note: an 'airing' is (programme id, start time); for this programme {int((dup > 1).sum())} of {len(dup)} start times occur on more than one channel")

# ---- V5: independent recount of the candidate pool of the test window --------------------------------------
say("\n## V5. Candidate pool of the test window recounted with the csv module")
lo, hi = dt.datetime(2020, 7, 27), dt.datetime(2020, 10, 19)
by_file = {}
for f in ("export_arh_11-20-final.csv", "export_arh_21-30-final.csv", "export_arh_31-42-final.csv"):
    ids = set()
    with open(RAW / f, encoding="utf-8", newline="") as fh:
        for r in csv.DictReader(fh):
            if r["tv_show_id"] != "0":
                t = dt.datetime.strptime(r["start_time"], "%d.%m.%Y %H:%M:%S")
                if lo <= t < hi:
                    ids.add(int(r["tv_show_id"]))
    by_file[f] = ids
sp_t = Split("test")
union = set().union(*by_file.values())
f31, f21 = by_file["export_arh_31-42-final.csv"], by_file["export_arh_21-30-final.csv"]
say(f"- csv-module recount over the three schedule files: file 31-42 alone {len(f31)} programmes; file 21-30 adds {len(f21 - f31)} more "
    f"(airings that start in the first hours of 2020-07-27; the files overlap in time but no row is in two files); union {len(union)} | "
    f"pipeline pool {len(sp_t.pool)} | identical sets: {union == set(sp_t.pool.tolist())}")

# ---- V6: seeds ----------------------------------------------------------------------------------------------
say("\n## V6. Sensitivity to the random seed (ALS, fold val, same split)")
sp, M, fb, D = data["val"]
res = []
for seed in (1, 2, 3, 4, 5):
    S = m.als_scores(M, factors=32, reg=150.0, alpha=1.0, iters=20, seed=seed)
    res.append(evaluate(m.recommend(M, S, fb), sp.truth, sp.users)["MAP@5"])
say(f"- ALS MAP@5 over seeds 1-5: {[round(x, 4) for x in res]}, mean {np.mean(res):.4f}, std {np.std(res):.4f}")
res2 = []
for seed in (1, 2, 3):
    p, _ = rr.crossfit_pooled(Ds_sub, n_users, rounds=ROUNDS, params=dict(LGB, seed=seed, bagging_seed=seed, feature_fraction_seed=seed))
    sp_, M_, fb_, D_ = data["val"]
    res2.append(evaluate(rr.lists_from_scores(sp_, M_, fb_, D_["rows"], D_["cols"], p[0]), sp_.truth, sp_.users)["MAP@5"])
say(f"- re-ranker MAP@5 (fold val) over LightGBM seeds 1-3: {[round(x, 4) for x in res2]}, std {np.std(res2):.4f}")

# ---- V7: candidate submission files ------------------------------------------------------------------------
say("\n## V7. Candidate submission files")
tmpl = pd.read_csv(RAW / "submission.csv", dtype={"user_id": "uint64"})
pool = set(sp_t.pool.tolist())
for f in ("submission_ltr_v2.csv", "submission_blend_v2.csv", "submitted_v1_ref57530793.csv"):
    sub = pd.read_csv(ROOT / "submissions" / f, dtype={"user_id": "uint64", "tv_show_id": str})
    lists = sub["tv_show_id"].str.split().apply(lambda l: [int(x) for x in l])
    ok = (len(sub) == 1260 and bool((sub["user_id"].values == tmpl["user_id"].values).all())
          and bool(lists.apply(lambda l: len(set(l)) == 5 and 0 not in l).all()))
    in_pool = bool(lists.apply(lambda l: set(l) <= pool).all())
    say(f"- {f}: 1260 rows, template order, 5 unique non-zero ids: {ok}; all ids in test-window pool: {in_pool}; md5 {hashlib.md5(open(ROOT / 'submissions' / f, 'rb').read()).hexdigest()}")

(ROOT / "results" / "verification_numbers_v2.md").write_text(buf.getvalue(), encoding="utf-8")
