"""Independent checks for the report section "What I personally checked".

Each check recomputes a number a second way (brute force on the raw files, or by hand-style steps) and
prints both. Output is also written to verification_numbers.md.
"""
import csv
import hashlib
import io
import contextlib
import numpy as np
import pandas as pd

import methods as m
from common import (Split, ROOT, K, W11, W23, W31, WATCH_ABS_S, WATCH_FRAC, ap_at_k, evaluate, load_interactions,
                    load_schedule, test_users)
from final import final_scores

RAW = ROOT / "data" / "raw"
buf = io.StringIO()


def say(*a):
    s = " ".join(str(x) for x in a)
    print(s)
    buf.write(s + "\n")


def count_rows(name):
    with open(RAW / name, encoding="utf-8", newline="") as fh:
        r = csv.reader(fh)
        next(r)
        return sum(1 for _ in r)


def ts(x):
    return pd.to_datetime(x, unit="s")


say("# Verification numbers (generated by src/verify.py)\n")

# ---- C1: raw file sizes and labelled share -----------------------------------------------------
say("## C1. Raw data against the task description")
spec = {"dataset11-30.csv": 5821987, "export_arh_11-20-final.csv": 1074235,
        "export_arh_21-30-final.csv": 1074394, "export_arh_31-42-final.csv": 1295378}
for f, n in spec.items():
    got = count_rows(f)
    say(f"- {f}: counted {got}, task says {n}, match={got == n}")
sched = load_schedule()
s1 = sched[sched["file"] == "11-20"]
say(f"- labelled share weeks 11-20: {(s1['tv_show_id'] != 0).sum()} of {len(s1)} = {100 * (s1['tv_show_id'] != 0).mean():.2f}% (task: 115,613 of 1,074,235 = 10.8%)")
say(f"- test users in template: {len(test_users())}")

# ---- C2: join cross-check by brute force ------------------------------------------------------
say("\n## C2. Log-to-schedule join: pipeline vs brute force on random views")
inter = load_interactions()
views = pd.read_csv(RAW / "dataset11-30.csv", nrows=400_000, dtype={"user_id": "uint64"})
views["s"] = pd.to_datetime(views["start_time"]).astype("datetime64[s]").astype(np.int64)
views["e"] = pd.to_datetime(views["stop_time"]).astype("datetime64[s]").astype(np.int64)
rng = np.random.default_rng(7)
ok_all, shown = True, 0
checked = 0
example = None
for ix in rng.permutation(len(views))[:3000]:
    v = views.iloc[ix]
    p = sched[(sched["file"] != "31-42") & (sched["channel_id"] == v["vsetv_id"]) & (sched["start_s"] < v["e"]) & (sched["end_s"] > v["s"])
              & (sched["tv_show_id"] != 0)]
    brute = sorted((int(r.tv_show_id), int(min(v["e"], r.end_s) - max(v["s"], r.start_s))) for r in p.itertuples())
    got = inter[(inter["user_id"] == v["user_id"]) & (inter["view_start_s"] == v["s"]) & (inter["channel_id"] == v["vsetv_id"])]
    pipe = sorted((int(a), int(b)) for a, b in zip(got["tv_show_id"], got["overlap_s"]))
    checked += 1
    same = brute == pipe
    ok_all &= same
    if brute and shown < 3:
        say(f"- view user {v['user_id']} channel {v['vsetv_id']} {ts(v['s'])} -> {ts(v['e'])}: brute force {brute} | pipeline {pipe} | equal={same}")
        if example is None:
            example = (v, p.iloc[0], brute[0])
        shown += 1
    if checked >= 400:
        break
say(f"- views compared: {checked}; all identical: {ok_all}")

# ---- C3: the watched threshold by hand on one airing ---------------------------------------------
say("\n## C3. 'Watched' rule by hand on one airing")
v, prog, (pid, ovs) = example
need = min(WATCH_ABS_S, WATCH_FRAC * prog["duration"])
say(f"- programme id {pid}, airing {ts(prog['start_s'])}, length {prog['duration']} s; user overlap {ovs} s")
say(f"- need min({WATCH_ABS_S}, {WATCH_FRAC} x {prog['duration']}) = {need} s -> counted as watched: {ovs >= need} (this single view only; several views of one airing are summed first)")

# ---- C4: leakage + independent recomputation of one user-item row ------------------------------
say("\n## C4. Time leakage and one train row recomputed from the raw log")
sp = Split("val")
d = sp.inter[(sp.inter["view_start_s"] >= sp.train_lo) & (sp.inter["view_start_s"] < sp.train_hi)]
say(f"- validation train uses views from {ts(d['view_start_s'].min())} to {ts(d['view_start_s'].max())} (cutoff {ts(W23)})")
vt = sp.inter[(sp.inter["view_start_s"] >= sp.tgt_lo) & (sp.inter["view_start_s"] < sp.tgt_hi)]
say(f"- validation truth uses views from {ts(vt['view_start_s'].min())} to {ts(vt['view_start_s'].max())}")
ui = sp.train_ui
row = ui.sort_values("sec", ascending=False).iloc[len(ui) // 50]
u, pid_ = row["user_id"], int(row["tv_show_id"])
full = pd.read_csv(RAW / "dataset11-30.csv", dtype={"user_id": "uint64"})
full = full[full["user_id"] == u]
full["s"] = pd.to_datetime(full["start_time"]).astype("datetime64[s]").astype(np.int64)
full["e"] = pd.to_datetime(full["stop_time"]).astype("datetime64[s]").astype(np.int64)
full = full[full["s"] < W23]
pr = sched[(sched["file"] != "31-42") & (sched["tv_show_id"] == pid_)]
tot, per = 0, {}
for r in pr.itertuples():
    fv = full[(full["vsetv_id"] == r.channel_id) & (full["s"] < r.end_s) & (full["e"] > r.start_s)]
    ov = int((np.minimum(fv["e"], r.end_s) - np.maximum(fv["s"], r.start_s)).sum()) if len(fv) else 0
    if ov > 0:
        per[(r.channel_id, r.start_s)] = (ov, r.duration)
good = {k: o for k, (o, dur) in per.items() if o >= min(WATCH_ABS_S, WATCH_FRAC * dur)}
say(f"- user {u}, programme {pid_}: raw-log brute force -> watched airings {len(good)}, seconds {sum(good.values())} | pipeline -> airings {int(row['n'])}, seconds {int(row['sec'])} | equal={len(good) == int(row['n']) and sum(good.values()) == int(row['sec'])}")

# ---- C5: MAP@5 by hand for two users ------------------------------------------------------------
say("\n## C5. AP@5 by hand for two validation users (final strategy)")
M = m.Matrices(sp)
fb = m.pop_ranking(sp.train_ui, sp.pool, "seconds")[:20]
rec = m.recommend(M, final_scores(M), fb)
titles = sched[sched["tv_show_id"] != 0].drop_duplicates("tv_show_id").set_index("tv_show_id")["tv_show_title"].to_dict()
cats = sched[sched["tv_show_id"] != 0].drop_duplicates("tv_show_id").set_index("tv_show_id")["tv_show_category"].to_dict()
cand = [x for x in sp.users if x in sp.truth and len(sp.truth[x]) == 5 and 0 < len(set(rec[x]) & set(sp.truth[x])) < 5]
for uu in cand[:2]:
    t_, r_ = sp.truth[uu], rec[uu]
    steps, hits, tot_ = [], 0, 0.0
    for i, x in enumerate(r_):
        if x in t_:
            hits += 1
            tot_ += hits / (i + 1)
            steps.append(f"pos {i + 1} hit -> precision {hits}/{i + 1} = {hits / (i + 1):.4f}")
        else:
            steps.append(f"pos {i + 1} miss")
    say(f"- user {uu}: truth {t_}; recommended {r_}")
    say(f"  " + "; ".join(steps) + f"; AP@5 = {tot_:.4f} / min(5,{len(t_)}) = {tot_ / min(5, len(t_)):.4f}; code ap_at_k = {ap_at_k(r_, t_):.4f}")
    say("  recommended: " + " | ".join(f"{x} {titles.get(x, '?')[:30]} [{cats.get(x, '?')}]" for x in r_))
ev = evaluate(rec, sp.truth, sp.users)
say(f"- whole validation set: {ev}")

# ---- C6: reproducibility of the final pipeline + submission file checks ------------------------
say("\n## C6. Re-run reproducibility and submission file")
sp_t = Split("test")
Mt = m.Matrices(sp_t)
fbt = m.pop_ranking(sp_t.train_ui, sp_t.pool, "seconds")[:20]
r1 = m.recommend(Mt, final_scores(Mt), fbt)
r2 = m.recommend(Mt, final_scores(Mt), fbt)
diff = sum(1 for u in sp_t.users if r1[u] != r2[u])
say(f"- two independent full runs (ALS refitted, seed 42): users with different lists = {diff} of {len(sp_t.users)}")
sub = pd.read_csv(ROOT / "submissions" / "submission_hybrid_v1.csv", dtype={"user_id": "uint64", "tv_show_id": str})
tmpl = pd.read_csv(RAW / "submission.csv", dtype={"user_id": "uint64"})
lists = sub["tv_show_id"].str.split().apply(lambda l: [int(x) for x in l])
pool = set(sp_t.pool.tolist())
say(f"- rows {len(sub)} (template {len(tmpl)}), same user order as template: {bool((sub['user_id'].values == tmpl['user_id'].values).all())}")
say(f"- every list has 5 unique ids: {bool(lists.apply(lambda l: len(set(l)) == 5).all())}; any id == 0: {bool(lists.apply(lambda l: 0 in l).any())}; all ids in test-window pool: {bool(lists.apply(lambda l: set(l) <= pool).all())}")
say(f"- users without training history (fallback to popularity): {int((~Mt.has_hist[Mt.sel]).sum())}")
say(f"- md5 of submission file: {hashlib.md5(open(ROOT / 'submissions' / 'submission_hybrid_v1.csv', 'rb').read()).hexdigest()}")

(ROOT / "results" / "verification_numbers.md").write_text(buf.getvalue(), encoding="utf-8")
